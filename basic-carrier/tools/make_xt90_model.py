"""Generate the XT90PW placeholder (3dmodels/xt90pw_21.00x25.40x10.20.wrl/.step).

Boxes only, but shaped so polarity can be seen in a STEP viewer:
- housing 21.0 x 25.4 x 10.2 mm; + side flat, GND side stepped ("chamfered" corners)
- a raised "+" on both end faces and on the outer face, over the + contact
- two pin stubs through the board at the pads, sticking ~1 mm out of the far side
Model axes = footprint axes: + (pad P, VBATT) at x = -5.45, GND (pad N) at x = +5.45.
The footprint places the model with offset (0,-1.1); pins are at footprint y +8.9.
Run: python tools/make_xt90_model.py   (then tools/wrl_box_to_step.py writes the .step)
"""
from pathlib import Path

U = 2.54
W, L, H = 21.0, 25.4, 10.2
PIN_Y_MODEL = 8.9 + 1.1   # model Y here matches footprint Y; the footprint applies offset -1.1 (checked in a render)
boxes = [  # (x0, x1, y0, y1, z0, z1, colour)
    (-W / 2, 7.0, -L / 2, L / 2, 0, H, (0.95, 0.85, 0.10)),          # main housing, + side flat
    (7.0, 8.75, -L / 2, L / 2, 0.7, H - 0.7, (0.95, 0.85, 0.10)),    # GND side step 1
    (8.75, W / 2, -L / 2, L / 2, 2.0, H - 2.0, (0.95, 0.85, 0.10)),  # GND side step 2
]
for ys, ye in ((L / 2, L / 2 + 0.3), (-L / 2 - 0.3, -L / 2)):       # "+" on both end faces
    boxes += [(-7.2, -3.7, ys, ye, 4.6, 5.6, (0.1, 0.1, 0.1)), (-5.95, -4.95, ys, ye, 3.35, 6.85, (0.1, 0.1, 0.1))]
boxes += [(-7.2, -3.7, -0.5, 0.5, H, H + 0.3, (0.1, 0.1, 0.1)), (-5.95, -4.95, -1.75, 1.75, H, H + 0.3, (0.1, 0.1, 0.1))]
for px in (-5.45, 5.45):                                             # pins through the board
    boxes.append((px - 1.0, px + 1.0, PIN_Y_MODEL - 1.0, PIN_Y_MODEL + 1.0, -2.6, 0, (0.85, 0.6, 0.2)))

out = ['#VRML V2.0 utf8', '# placeholder xt90pw_21.00x25.40x10.20: 21.00 x 25.40 x 10.20 mm, + flat side at -x, '
       'stepped GND side at +x, "+" marks, pin stubs (generated by tools/make_xt90_model.py)']
for x0, x1, y0, y1, z0, z1, c in boxes:
    p = [(x, y, z) for z in (z0, z1) for (x, y) in ((x0, y0), (x1, y0), (x1, y1), (x0, y1))]
    pts = ', '.join('%.4f %.4f %.4f' % (x / U, y / U, z / U) for x, y, z in p)
    out.append('Shape {\n appearance Appearance { material Material { diffuseColor %.2f %.2f %.2f } }\n'
               ' geometry IndexedFaceSet {\n  coord Coordinate { point [ %s ] }\n'
               '  coordIndex [ 0 3 2 1 -1, 4 5 6 7 -1, 0 1 5 4 -1, 1 2 6 5 -1, 2 3 7 6 -1, 3 0 4 7 -1 ]\n }\n}' % (c + (pts,)))
Path(__file__).resolve().parent.parent.joinpath('3dmodels', 'xt90pw_21.00x25.40x10.20.wrl').write_text('\n'.join(out) + '\n')
print('wrote', len(boxes), 'boxes')
